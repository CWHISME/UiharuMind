namespace UiharuMind.Core.AI.Execution.Prompts;

/// <summary>
/// 子代理系统提示里「子代理专属」的那些句子，唯一出处。
///
/// 与主代理侧的 <see cref="AgentToolPrompts"/> 对应：这里只收身份与协作口径；
/// 工具纪律（文件、命令行、Python、草稿目录、工作目录）两档<b>共用主代理那份</b>，
/// 由段落清单统一编排，不在这里重复定义。
///
/// <b>从前的「# 做法」段已拆掉</b>：那一段把「你能用哪些工具」与「你该怎么协作」
/// 混成一摊平级 bullet，于是 shell 纪律和「回复要聚焦」并排出现，
/// 而主代理侧同样的内容是有 <c>## 命令行</c> 标题的——同一件事两种层级。
/// </summary>
public static class SubAgentPrompts
{
    /// <summary>
    /// 身份段首句。<b>点名的子智能体不发这一句</b>：它自己的角色卡已经说过它是谁，
    /// 再跟一句"你是 UiharuMind 的一个代理"就是跟人格抢身份（与 ADR 0005 同一道理）。
    ///
    /// 措辞从"独立完成派给你的任务，然后交回结论"改过来：那是一次性交活的框架，
    /// 而基础设施早就按多轮讨论设计了（<c>BackgroundSubAgentDispatcher.MaxConsecutiveWakeTurns</c>
    /// 取 32 的理由原话就是"主、子代理多轮讨论时 12 轮不够一次讨论收敛"）。
    /// 提示词说"独立"、代码等着你来回谈，冲突的是提示词。
    /// </summary>
    public const string Role = "你是 UiharuMind 的一个代理，受另一个代理委派处理一件事。";

    /// <summary>
    /// 派活时给的一句话身份。
    ///
    /// <b>落点是"判断标准"而不是"扮演"</b>：身份提示当能力暗示用（"你是专家所以你更准"）
    /// 证据很弱；真正起作用的是它收窄了关注点与取舍口径。而本地小模型对文体极敏感，
    /// 一句"请始终以这个身份思考和回应"很可能换来角色腔的汇报而不是干活。
    /// </summary>
    /// <param name="role">派活方给的身份</param>
    /// <returns>身份句</returns>
    public static string RoleAssignment(string role) =>
        $"你这次的身份：{role}。按这个身份的视角和判断标准来做这件事。";

    /// <summary>
    /// 身份句的补充，<b>只在人格卡也在场时追加</b>。
    ///
    /// 不表态的话，一张写得强势的角色卡（长度与具体度都碾压那一句 role）会直接压过它，
    /// 于是"点名一个代理 + 给它本次侧重"这个组合又变成半死的。
    /// </summary>
    public const string RoleOverPersona = "这一趟按这个侧重来，其余仍按你自己的方式。";

    /// <summary>可变更档的边界。从前与「档位提示」近乎逐字重复，那一份已删</summary>
    public const string BoundaryCanMutate =
        "你可以改东西（文件、命令、MCP），但只改这件事要求的那些，别的一概不动。";

    /// <summary>只读档的边界</summary>
    public const string BoundaryReadOnly =
        "你是只读的：写不了文件、没有 shell。该改什么，在回应里写清楚。";

    /// <summary>
    /// 协作段正文。四条改动，每条都对着一处实际冲突：
    ///
    /// 1. <b>讨论是常态</b>——取代从前"不必每轮都交终版结论"那句附带说明，
    ///    现在它是第一条，因为 <see cref="Role"/> 不再说"独立完成"了。
    /// 2. <b>用户可能直接插话</b>——子代理从前完全不知道这件事，会把用户的话
    ///    当成派活方的追问。主代理侧倒是知道（<see cref="AgentToolPrompts.SubAgentDefault"/> 末条）。
    /// 3. <b>缺信息不再强制停</b>——从前写死"以'需要你补充：'开头…然后结束本轮等追问"，
    ///    既钉死了句式，又把"先做能做的"这条路堵了。保留的是"不要猜着补"。
    /// 4. <b>回复格式降为默认</b>——"先结论再依据"是交终版时的好默认，
    ///    讨论轮里按它写很别扭。
    ///
    /// 末条<b>一字未动</b>：它不是风格，它对着代码兜底（模型以工具调用收尾时，
    /// 要额外追加一轮 <see cref="SummaryPrompt"/>），松了就是每次白烧一轮。
    /// </summary>
    public const string Collaboration =
        "- 派活方会就这件事继续追问、纠偏、和你讨论。这不是一次性交活：\n" +
        "  哪一轮交终版结论、哪一轮只是往下谈，你自己判断。\n" +
        "- 用户也可能直接在这个窗口对你说话。那不是派活方的话，按你自己的判断回应。\n" +
        "- 任务里没给的信息不要猜着补。缺什么就说缺什么——可以先做能做的部分，也可以直接问回去。\n" +
        "- 需要审批的操作会问到用户那里，正常请求即可。\n" +
        "- 交终版结论时先给结论、再给依据（路径、链接、原文）；讨论轮里不必套这个格式。\n" +
        "- 每一轮都要以一段文本收尾，不要让工具调用做最后一个动作。";

    /// <summary>代码兜底追加总结轮时的提问</summary>
    public const string SummaryPrompt = "请用一段话总结这一轮的发现和结论，作为本轮结论。";
}
