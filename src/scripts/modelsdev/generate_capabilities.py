#!/usr/bin/env python3
"""Generate ModelCapabilityTable.g.cs from models.dev/api.json.

models.dev is a build-time capability DB (MIT). We only keep the fields the
model editor prefills: vision, max output, context, and whether temperature is
fixed. Run this when adding a provider or refreshing the table; commit the
generated .g.cs together with the script.

Usage:
  python generate_capabilities.py
  python generate_capabilities.py --input /path/to/api.json
"""

import argparse
import json
import os
import sys
import urllib.request

PROVIDERS = ["agnes", "deepseek", "sensenova", "zhipuai", "commandcode", "opencode", "opencode-go"]
URL = "https://models.dev/api.json"

# 配置类型 → models.dev provider 键。新增供应商时同步这里。
PROVIDER_TYPES = [
    ("RemoteAgnesModelConfig", "agnes"),
    ("RemoteDeepSeekModelConfig", "deepseek"),
    ("RemoteSensenovaModelConfig", "sensenova"),
    ("RemoteZhipuModelConfig", "zhipuai"),
    ("RemoteCommandCodeModelConfig", "commandcode"),
    ("RemoteOpenCodeModelConfig", "opencode"),
]


def load(input_path):
    if input_path:
        with open(input_path, encoding="utf-8") as f:
            return json.load(f)
    with urllib.request.urlopen(URL, timeout=60) as r:
        return json.load(r)


def escape(value):
    return value.replace("\\", "\\\\").replace('"', '\\"')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", help="本地 api.json；缺省从 models.dev 下载")
    parser.add_argument(
        "--output",
        default=os.path.join(
            os.path.dirname(__file__), "..", "..", "UiharuMind.Core", "RemoteOpenAI", "ModelCatalog",
            "ModelCapabilityTable.g.cs",
        ),
    )
    args = parser.parse_args()

    data = load(args.input)
    rows = []
    for provider in PROVIDERS:
        p = data.get(provider)
        if not p:
            print(f"skip missing provider: {provider}", file=sys.stderr)
            continue
        for model_id, m in (p.get("models") or {}).items():
            modalities = m.get("modalities") or {}
            limit = m.get("limit") or {}
            vision = "image" in (modalities.get("input") or [])
            max_out = int(limit.get("output") or 0)
            ctx = int(limit.get("context") or 0)
            omit = m.get("temperature") is False
            rows.append((provider, model_id, vision, max_out, ctx, omit))

    rows.sort(key=lambda r: (r[0], r[1]))

    out = [
        "// <auto-generated>",
        "// Generated from models.dev/api.json by src/scripts/modelsdev/generate_capabilities.py.",
        "// Do not edit by hand; re-run the script instead.",
        "// </auto-generated>",
        "",
        "using UiharuMind.Core.Configs.RemoteAI;",
        "",
        "namespace UiharuMind.Core.RemoteOpenAI.ModelCatalog;",
        "",
        "/// <summary>",
        "/// models.dev 静态能力表（构建期生成）：目录不携带能力字段时用它兜底。",
        "/// 键是 <c>provider/modelId</c>；只保留编辑窗口预填要用的四项。",
        "/// </summary>",
        "internal static class ModelCapabilityTable",
        "{",
        "    internal readonly record struct Capability(bool IsVision, int MaxTokens, int ContextLength, bool OmitSamplingParams);",
        "",
        "    private static readonly Dictionary<string, Capability> Entries = new(StringComparer.OrdinalIgnoreCase)",
        "    {",
    ]
    for provider, model_id, vision, max_out, ctx, omit in rows:
        key = escape(f"{provider}/{model_id}")
        out.append(f'        ["{key}"] = new({str(vision).lower()}, {max_out}, {ctx}, {str(omit).lower()}),')
    out += [
        "    };",
        "",
        "    internal static bool TryGet(string providerKey, string modelId, out Capability capability) =>",
        '        Entries.TryGetValue(providerKey + "/" + modelId, out capability);',
        "",
        "    /// <summary>配置类型 → models.dev 的 provider 键；未知返回空串</summary>",
        "    internal static string ProviderKeyOf(Type configType) => configType switch",
        "    {",
    ]
    for type_name, provider in PROVIDER_TYPES:
        out.append(f'        _ when configType == typeof({type_name}) => "{provider}",')
    out += [
        '        _ => "",',
        "    };",
        "}",
        "",
    ]

    path = os.path.normpath(args.output)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {path}: {len(rows)} entries")


if __name__ == "__main__":
    main()
