namespace UiharuMind.Core.AI.Character;

// 角色库导航列表的筛选轴。两条，各自封闭。下面两条枚举共用下面这段理由。
//
// 为什么是封闭枚举，而不是给角色加一个「标签」功能——这条路问过、也走过一遍模型，结论是不走：
//
//   · 标签解的是「一张卡带任意多个不互斥的作者自定义属性」，那是知识库与文档的需求。
//     角色库要的是几个会互相排斥、且代码要拿来查的分类轴：是不是内置、什么档位、同什么 IP、
//     群里的定位。角色只有几十张、集合封闭，开放字符串付不起这个成本。
//   · 标签最贵的部分不是界面，是同义项分裂：魔禁 / 某科学的超电磁炮 / Index 会长成三个
//     互相漏筛的标签，去重只能靠人。
//   · 「A 认识 B」那种有向关系标签天生表达不了：单边存得到的是半信息的对称关系。
//     真要那种边，形状该照 CharacterData.MountAgents 抄（有向、可解析到 CharacterId），
//     而不是新造一个字符串字段——而那件事等真在群里观察到「认不出在场的人」再开。
//
// 所以这里是「加轴」而不是「加标注」：多一个维度就是多一条新枚举。
// 通用标签唯一站得住的位置是 SillyTavern 导入的元数据（CharacterCardV3.Data.Tags），
// 那是外部数据的映射，与角色模型无关。

/// <summary>
/// 角色库导航列表的<b>档位</b>筛选轴。角色身份只有这一条轴（ADR 0043），
/// 所以这一轴的全部选项就是「全部 / 普通角色 / 智能体」。
///
/// 成员值<b>刻意等于旧版下标数组的下标</b>（全部 0 / 普通角色 1 / 智能体 2）：
/// 那个数组的下标曾直接落进用户设置，换成枚举后同一个数字仍然指同一档，
/// 升级不必迁移，也不必做旧值映射。往后新增成员必须显式给值，不能靠声明顺序——
/// 靠顺序加一个成员，就等于把老用户已选的那一档悄悄改成了另一档。
/// </summary>
public enum ECharacterKindFilter
{
    /// <summary>不按档位筛</summary>
    All = 0,

    /// <summary>只看普通角色</summary>
    Chat = 1,

    /// <summary>只看智能体</summary>
    Agent = 2,
}

/// <summary>
/// 角色库导航列表的<b>来源</b>筛选轴：这张卡是随程序内置的，还是用户自己建的。
///
/// 与 <see cref="ECharacterKindFilter"/> <b>正交</b>——内置卡里也有普通角色与智能体
/// （<see cref="DefaultCharacterManager"/> 扫的 <c>Resources/Cards/</c> 三类都有），
/// 所以两条轴各筛各的，<b>不合成一张互斥表</b>：合成的话「我的智能体」这一格就没了。
///
/// 存在的理由是角色库会把两类卡混排在一条列表里，而用户分不出眼前这张是内置的还是自己建的。
/// 判据取 <see cref="CharacterData.IsBuiltIn"/> 而不取「文件在哪」：内置卡被改过之后
/// 会落到用户目录（覆盖路径只认 <see cref="DefaultCharacter"/> 枚举里的那些，内容卡不在其中），
/// 但它仍然是内置卡，来源筛选该把它算在内。
/// </summary>
public enum ECharacterOriginFilter
{
    /// <summary>不按来源筛</summary>
    All = 0,

    /// <summary>只看随程序内置的卡</summary>
    BuiltIn = 1,

    /// <summary>只看用户自己建的卡</summary>
    Mine = 2,
}
